#!/usr/bin/env python3
"""根据 JSON 生成可复核的 Lumerical GDS 几何重建 LSF 脚本。

生成的 LSF 对每个声明的工艺层调用一次原生 ``gdsimport``。本脚本不执行
Lumerical、不修改源 GDS，也不猜测材料和 Z 边界。应先运行
``audit_gds_geometry.py``，再把每个必需的 ``layer:datatype`` 显式映射到
材料和可选的三维拉伸范围。

可复用用途：把已审计的 GDS/工艺层映射转换为可移植 LSF 重建文件，供
FDTD、MODE、EME 或 varFDTD Layout 工程使用。
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


def _lsf_string(value: str) -> str:
    return '"' + value.replace("\\", "/").replace('"', '\\"') + '"'


def _number(value: Any, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{label} must be numeric")
    return float(value)


def _load_config(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("configuration root must be an object")
    return payload


def build_lsf(config: dict[str, Any], config_path: Path) -> str:
    source_value = config.get("source_gds")
    cell = config.get("cell")
    layers = config.get("layers")
    if not isinstance(source_value, str) or not source_value:
        raise ValueError("source_gds is required")
    if not isinstance(cell, str) or not cell:
        raise ValueError("cell is required")
    if not isinstance(layers, list) or not layers:
        raise ValueError("layers must be a nonempty array")

    source = Path(source_value)
    if not source.is_absolute():
        source = (config_path.parent / source).resolve()
    else:
        source = source.resolve()

    lines = [
        "# Generated by generate_gds_import_lsf.py.",
        "# Layout-only reconstruction: no run, runsweep, emesweep, findmodes, save, or switchtolayout.",
        "clear;",
        f"source_gds = {_lsf_string(str(source))};",
        f"source_cell = {_lsf_string(cell)};",
        "if (!fileexists(source_gds)) {",
        '    error("GDS source not found: " + source_gds);',
        "}",
        "imported_total = 0;",
        "",
    ]

    for index, layer in enumerate(layers, start=1):
        if not isinstance(layer, dict):
            raise ValueError(f"layers[{index}] must be an object")
        layer_spec = layer.get("layer")
        if not isinstance(layer_spec, (str, int)) or isinstance(layer_spec, bool):
            raise ValueError(f"layers[{index}].layer must be a layer or layer:datatype")
        material = layer.get("material")
        if material is not None and (not isinstance(material, str) or not material):
            raise ValueError(f"layers[{index}].material must be a nonempty string")
        has_z_min = "z_min_m" in layer
        has_z_max = "z_max_m" in layer
        if has_z_min != has_z_max:
            raise ValueError(f"layers[{index}] must define both z_min_m and z_max_m")
        if has_z_min and material is None:
            raise ValueError(f"layers[{index}] needs material when Z bounds are used")

        layer_argument = (
            _lsf_string(layer_spec) if isinstance(layer_spec, str) else str(layer_spec)
        )
        arguments = ["source_gds", "source_cell", layer_argument]
        if material is not None:
            arguments.append(_lsf_string(material))
        if has_z_min:
            z_min = _number(layer["z_min_m"], f"layers[{index}].z_min_m")
            z_max = _number(layer["z_max_m"], f"layers[{index}].z_max_m")
            if z_max <= z_min:
                raise ValueError(f"layers[{index}] requires z_max_m > z_min_m")
            arguments.extend([f"{z_min:.17g}", f"{z_max:.17g}"])

        description = layer.get("description", f"layer {layer_spec}")
        if not isinstance(description, str):
            raise ValueError(f"layers[{index}].description must be a string")
        lines.extend(
            [
                f"# {description}",
                f"imported_count = gdsimport({', '.join(arguments)});",
                "if (imported_count < 1) {",
                f"    error({_lsf_string(f'No objects imported for {layer_spec}')});",
                "}",
                "imported_total = imported_total + imported_count;",
                "",
            ]
        )

    lines.extend(
        [
            '?"------------------------------------------------------------";',
            '?"GDS reconstruction completed in the current Layout session";',
            '?"source: " + source_gds;',
            '?"cell: " + source_cell;',
            '?"imported objects: " + num2str(imported_total);',
            '?"------------------------------------------------------------";',
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path, help="UTF-8 JSON 工艺层映射")
    parser.add_argument("--output", type=Path, help="生成的 .lsf 文件路径")
    parser.add_argument(
        "--allow-overwrite",
        action="store_true",
        help="覆盖已存在的生成 LSF",
    )
    args = parser.parse_args()

    config_path = args.config.resolve()
    config = _load_config(config_path)
    output = (
        args.output.resolve()
        if args.output
        else config_path.with_suffix(".gds_import.lsf")
    )
    if output.exists() and not args.allow_overwrite:
        parser.error(f"output already exists: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_lsf(config, config_path), encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
